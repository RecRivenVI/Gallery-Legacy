// Generates the wire records used by the Go service and Compose clients.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

type field struct{ Name, Go, Type, GoType, Default string }
type model struct {
	Name    string
	Generic string
	Fields  []field
	Row     bool
}
type contract struct{ Models []model }

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	data, err := os.ReadFile("public.json")
	if err != nil {
		return err
	}
	var schema contract
	if err = json.Unmarshal(data, &schema); err != nil {
		return err
	}
	configModels, err := configurationModels()
	if err != nil {
		return err
	}
	schema.Models = append(schema.Models, configModels...)
	goTypes := map[string]string{"int": "int", "long": "int64", "string": "string", "nullableString": "*string", "bool": "bool", "strings": "[]string", "longMap": "map[string]int64", "object": "map[string]any"}
	goTypes["objects"], goTypes["jsonValue"] = "[]map[string]any", "any"
	ktTypes := map[string]string{"int": "Int", "long": "Long", "string": "String", "nullableString": "String?", "bool": "Boolean", "strings": "List<String>", "longMap": "Map<String, Long>", "object": "JsonElement?"}
	ktTypes["objects"], ktTypes["jsonValue"] = "List<JsonElement>", "JsonElement?"
	goTypes["nullableLong"], goTypes["nullableBool"] = "*int64", "*bool"
	ktTypes["nullableLong"], ktTypes["nullableBool"] = "Long?", "Boolean?"
	goTypes["stringMap"], ktTypes["stringMap"] = "map[string]string", "Map<String, String>"
	goTypes["float"], ktTypes["float"] = "float32", "Float"
	for _, m := range schema.Models {
		goTypes[m.Name] = m.Name
		ktTypes[m.Name] = m.Name + "Wire"
	}
	var goOut, ktOut bytes.Buffer
	fmt.Fprintln(&goOut, "// Code generated by go generate ./api from public.json. DO NOT EDIT.\npackage api")
	fmt.Fprintln(&ktOut, "// Code generated by go generate ./api from api/public.json, protocol.json and catalog.json. DO NOT EDIT.\npackage gallery\n\nimport kotlinx.serialization.Serializable\nimport kotlinx.serialization.json.*")
	for _, m := range schema.Models {
		goName, ktName := m.Name, m.Name+"Wire"
		if m.Generic != "" {
			goName += "[" + m.Generic + " any]"
			ktName += "<" + m.Generic + ">"
			goTypes[m.Generic] = m.Generic
			ktTypes[m.Generic] = m.Generic
		}
		fmt.Fprintf(&goOut, "\ntype %s struct {\n", goName)
		fmt.Fprintf(&ktOut, "\n@Serializable\ndata class %s(\n", ktName)
		for _, f := range m.Fields {
			goType, ktType := goTypes[f.Type], ktTypes[f.Type]
			if strings.HasPrefix(f.Type, "nullable:") {
				name := strings.TrimPrefix(f.Type, "nullable:")
				goType = "*" + goTypes[name]
				ktType = ktTypes[name] + "?"
			}
			if strings.HasPrefix(f.Type, "list:") {
				name := strings.TrimPrefix(f.Type, "list:")
				goType = "[]" + goTypes[name]
				ktType = "List<" + ktTypes[name] + ">"
			}
			if goType == "" || ktType == "" {
				return fmt.Errorf("unknown wire type %s", f.Type)
			}
			if f.GoType != "" {
				goType = f.GoType
			}
			fallback := ""
			switch {
			case strings.HasSuffix(ktType, "?"):
				fallback = "null"
			case ktType == "String":
				fallback = `""`
			case ktType == "Boolean":
				fallback = "false"
			case ktType == "Int":
				fallback = "0"
			case ktType == "Long":
				fallback = "0L"
			case ktType == "Float":
				fallback = "0f"
			case strings.HasPrefix(ktType, "List<"):
				fallback = "emptyList()"
			case strings.HasPrefix(ktType, "Map<"):
				fallback = "emptyMap()"
			default:
				fallback = ktType + "()"
			}
			if f.Default != "" {
				fallback = f.Default
			}
			fmt.Fprintf(&goOut, "%s %s `json:%q`\n", f.Go, goType, f.Name)
			fmt.Fprintf(&ktOut, "    val %s: %s = %s,\n", f.Name, ktType, fallback)
		}
		fmt.Fprintln(&goOut, "}")
		if m.Row {
			fmt.Fprintf(&goOut, "func (value %s) Row() map[string]any { return map[string]any{", m.Name)
			for _, f := range m.Fields {
				fmt.Fprintf(&goOut, "%q:value.%s,", f.Name, f.Go)
			}
			fmt.Fprintln(&goOut, "} }")
		}
		fmt.Fprintln(&ktOut, ")")
		if m.Generic == "" {
			fmt.Fprintf(&ktOut, "\nfun %sWire(raw: JsonElement?): %sWire = json.decodeFromJsonElement(raw ?: emptyDocument)\n", m.Name, m.Name)
		}
	}
	var protocol map[string]json.RawMessage
	data, err = os.ReadFile("protocol.json")
	if err != nil {
		return err
	}
	if err = json.Unmarshal(data, &protocol); err != nil {
		return err
	}
	for _, key := range []string{"workSorts", "authorSorts", "mediaFilters", "runtimeStates", "scanStates"} {
		var values []string
		if err = json.Unmarshal(protocol[key], &values); err != nil {
			return err
		}
		writeList(&ktOut, "protocol"+strings.ToUpper(key[:1])+key[1:], values)
	}
	var catalog struct {
		Platforms []struct {
			ID string `json:"id"`
		}
	}
	data, err = os.ReadFile("catalog.json")
	if err != nil {
		return err
	}
	if err = json.Unmarshal(data, &catalog); err != nil {
		return err
	}
	var ids []string
	for _, p := range catalog.Platforms {
		ids = append(ids, p.ID)
	}
	writeList(&ktOut, "platforms", ids)
	formatted, err := format.Source(goOut.Bytes())
	if err != nil {
		return err
	}
	if err = os.WriteFile("public_generated.go", formatted, 0644); err != nil {
		return err
	}
	var desktop struct {
		App struct {
			Security struct {
				CSP string `json:"csp"`
			} `json:"security"`
		} `json:"app"`
	}
	data, err = os.ReadFile("../src-tauri/tauri.conf.json")
	if err != nil {
		return err
	}
	if err = json.Unmarshal(data, &desktop); err != nil {
		return err
	}
	policy := fmt.Sprintf("// Code generated by go generate ./api from src-tauri/tauri.conf.json. DO NOT EDIT.\npackage api\nconst BrowserCSP = %q\n", desktop.App.Security.CSP)
	policySource, err := format.Source([]byte(policy))
	if err != nil {
		return err
	}
	if err = os.WriteFile("security_generated.go", policySource, 0644); err != nil {
		return err
	}
	return os.WriteFile(filepath.FromSlash("../ui/src/commonMain/kotlin/gallery/ProtocolGenerated.kt"), ktOut.Bytes(), 0644)
}

func writeList(out *bytes.Buffer, name string, values []string) {
	fmt.Fprintf(out, "\nval %s = listOf(", name)
	for i, value := range values {
		if i > 0 {
			fmt.Fprint(out, ", ")
		}
		fmt.Fprintf(out, "%q", value)
	}
	fmt.Fprintln(out, ")")
}
